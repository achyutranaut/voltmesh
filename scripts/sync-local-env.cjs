#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const localDeployPath = path.join(rootDir, 'contracts/deployments/local.json');

if (!fs.existsSync(localDeployPath)) {
  console.error(`ERROR: ${localDeployPath} not found.`);
  process.exit(1);
}

const local = JSON.parse(fs.readFileSync(localDeployPath, 'utf8'));

// 1. Generate apps/web/.env.local
const webEnvPath = path.join(rootDir, 'apps/web/.env.local');
const webEnvContent = `# Auto-generated by VoltMesh local-demo.sh on ${new Date().toISOString()}
# DO NOT COMMIT TO VERSION CONTROL

VITE_CHAIN_ID=31337
VITE_RPC_URL=http://127.0.0.1:8545
VITE_API_URL=http://localhost:3000
VITE_USE_LOCAL=true
VITE_DEMO_MODE=true

VITE_ACCESS_REGISTRY_ADDRESS=${local.AccessRegistry}
VITE_PARTICIPANT_REGISTRY_ADDRESS=${local.ParticipantRegistry}
VITE_DEVICE_REGISTRY_ADDRESS=${local.DeviceRegistry}
VITE_EPOCH_ORACLE_ADDRESS=${local.EpochOracle}
VITE_MOCK_ERC20_ADDRESS=${local.MockERC20}
VITE_ESCROW_ADDRESS=${local.Escrow}
VITE_BATCH_SETTLEMENT_ADDRESS=${local.BatchSettlement}
VITE_CERTIFICATE_REGISTRY_ADDRESS=${local.CertificateRegistry}
VITE_RETIREMENT_REGISTRY_ADDRESS=${local.RetirementRegistry}
`;

fs.writeFileSync(webEnvPath, webEnvContent, 'utf8');
console.log(`      Written: ${path.relative(rootDir, webEnvPath)}`);

// 2. Generate services/api/.env.local
const apiEnvPath = path.join(rootDir, 'services/api/.env.local');
const apiEnvContent = `# Auto-generated by VoltMesh local-demo.sh on ${new Date().toISOString()}
# DO NOT COMMIT TO VERSION CONTROL

NODE_ENV=development
PORT=3000
CHAIN_ID=31337
RPC_URL=http://127.0.0.1:8545

ACCESS_REGISTRY_ADDRESS=${local.AccessRegistry}
PARTICIPANT_REGISTRY_ADDRESS=${local.ParticipantRegistry}
DEVICE_REGISTRY_ADDRESS=${local.DeviceRegistry}
EPOCH_ORACLE_ADDRESS=${local.EpochOracle}
MOCK_ERC20_ADDRESS=${local.MockERC20}
ESCROW_ADDRESS=${local.Escrow}
BATCH_SETTLEMENT_ADDRESS=${local.BatchSettlement}
CERTIFICATE_REGISTRY_ADDRESS=${local.CertificateRegistry}
RETIREMENT_REGISTRY_ADDRESS=${local.RetirementRegistry}

# Role Accounts for Local Devnet (Anvil public accounts 1-5):
# Account 1: Regulator
REGULATOR_ADDRESS=0x70997970C51812dc3A010C7d01b50e0d17dc79C8
# Account 2: Market Operator (backend sign key)
OPERATOR_ADDRESS=0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC
OPERATOR_PRIVATE_KEY=0x5de4111afa1a4b94908f83103eb1f1706367c2e68ca870fc3fb9a804cdab365a
# Account 3: Oracle
ORACLE_ADDRESS=0x90F79bf6EB2c4f870365E785982E1f101E93b906
ORACLE_PRIVATE_KEY=0x7c852118294e51e653712a81e05800f419141751be58f605c371e15141b007a6
# Account 4: Seller
SELLER_ADDRESS=0x15d34AAf54267DB7D7c367839AAf71A00a2C6A65
# Account 5: Buyer
BUYER_ADDRESS=0x9965507D1a55bcC2695C58ba16FB37d819B0A4dc

JWT_SECRET=voltmesh-local-demo-jwt-secret-minimum-32-characters-required
ALLOW_DEV_KEYS=true
SANDBOX_MODE=true
`;

fs.writeFileSync(apiEnvPath, apiEnvContent, 'utf8');
console.log(`      Written: ${path.relative(rootDir, apiEnvPath)}`);

// 3. Update apps/web/src/contracts/deployments.json for fallback compatibility
const webDeployJsonPath = path.join(rootDir, 'apps/web/src/contracts/deployments.json');
if (fs.existsSync(webDeployJsonPath)) {
  const webDeploy = JSON.parse(fs.readFileSync(webDeployJsonPath, 'utf8'));
  webDeploy.chainId = 31337;
  webDeploy.rpcUrl = 'http://127.0.0.1:8545';
  if (webDeploy.contracts) {
    for (const [key, addr] of Object.entries(local)) {
      if (webDeploy.contracts[key]) {
        webDeploy.contracts[key].address = addr;
      }
    }
  }
  fs.writeFileSync(webDeployJsonPath, JSON.stringify(webDeploy, null, 2), 'utf8');
  console.log(`      Updated: ${path.relative(rootDir, webDeployJsonPath)}`);
}
